# "동의어 -> 표준어"로 뒤집고, 긴 표현부터 매칭되도록 길이 내림차순 정렬
# (짧은 표현이 긴 표현의 일부를 잘못 선매칭하는 것 방지)
_VARIANT_TO_CANONICAL = {
    variant.lower(): canonical
    for canonical, variants in SYNONYM_MAP.items()
    for variant in variants
}
_PATTERN = re.compile(
    "|".join(re.escape(v) for v in sorted(_VARIANT_TO_CANONICAL, key=len, reverse=True)),
    re.IGNORECASE,
)


def normalize_terms(text: str) -> str:
    """질문 속 동의어를 PDF 표준 용어로 치환. 예: '헤드램프 켜는 법' -> '전조등 켜는 법'"""
    return _PATTERN.sub(lambda m: _VARIANT_TO_CANONICAL[m.group(0).lower()], text)


